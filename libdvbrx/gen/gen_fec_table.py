#!/usr/bin/env python3
"""Generate fec_table.h (BCH k/n/t per frame size and code rate) from
gr-dvbs2rx's fec_params.cc.

usage: gen_fec_table.py <fec_params.cc> > src/fec_table.h
"""
import re
import sys

src = open(sys.argv[1]).read()
sections = {"NORMAL": src[src.index("FECFRAME_NORMAL"):src.index("FECFRAME_SHORT")],
            "SHORT": src[src.index("FECFRAME_SHORT"):src.index("fec_info.ldpc.n = 32400")]}
case_re = re.compile(r"case (C\w+):\s*(?:case (C\w+):\s*)*"
                     r"fec_info\.bch\.k = (\d+);\s*fec_info\.bch\.n = (\d+);\s*"
                     r"fec_info\.bch\.t = (\d+);")
print("/* Generated by gen/gen_fec_table.py from gr-dvbs2rx fec_params.cc. */")
print("/* { rate, kbch, nbch, t } */")
for name, text in sections.items():
    print(f"static const struct fec_row fec_{name.lower()}[] = {{")
    for m in case_re.finditer(text):
        labels = re.findall(r"case (C\w+):", m.group(0))
        k, n, t = m.group(3), m.group(4), m.group(5)
        for lab in labels:
            print(f'    {{ "{lab[1:]}", {k}, {n}, {t} }},')
    print("};")
