#!/usr/bin/env python3
"""Generate ldpc_tables.h (DVB-S2/S2X and DVB-T2 parity-check address tables
and the rate -> table mapping) from gr-dvbs2rx's dvb_s2_tables.hh,
dvb_s2x_tables.hh, dvb_t2_tables.hh and ldpc_decoder_bb_impl.cc.

DVB-T2 uses the DVB-S2 codes except for two, named "2_3_t2" (normal
frames, EN 302 755 table A.3) and "3_5_t2" (short frames, table B.3).

usage: gen_ldpc_tables.py <gr-dvbs2rx/lib> > src/ldpc_tables.h
"""
import os
import re
import sys

lib = sys.argv[1]
tables = {}
for name in ("dvb_s2_tables.hh", "dvb_s2x_tables.hh", "dvb_t2_tables.hh"):
    src = open(os.path.join(lib, name)).read()
    for m in re.finditer(r"struct (\w+) \{(.*?)\n\};", src, re.S):
        body = m.group(2)

        def num(field):
            return int(re.search(rf"\b{field} = (\d+);", body).group(1))

        def arr(field):
            a = re.search(rf"\b{field}\[\] = \{{(.*?)\}};", body, re.S).group(1)
            return [int(x) for x in re.findall(r"\d+", a)]

        tables[m.group(1)] = dict(M=num("M"), N=num("N"), K=num("K"),
                                  LINKS_MAX_CN=num("LINKS_MAX_CN"),
                                  LINKS_TOTAL=num("LINKS_TOTAL"),
                                  DEG_MAX=num("DEG_MAX"), DEG=arr("DEG"),
                                  LEN=arr("LEN"), POS=arr("POS"))

impl = open(os.path.join(lib, "ldpc_decoder_bb_impl.cc")).read()
normal = impl[impl.index("FECFRAME_NORMAL"):impl.index("FECFRAME_SHORT")]
short = impl[impl.index("FECFRAME_SHORT"):]
short = short[:short.index("default")]


def mapping(text):
    out = []
    # "case Cx:" followed by the first LDPC<...> (the DVB-S2 branch)
    for m in re.finditer(r"case C(\w+):(.*?)break;", text, re.S):
        t = re.search(r"LDPC<(\w+)>", m.group(2))
        if t:
            out.append((m.group(1), t.group(1)))
    return out


T2_NORMAL = [("2_3_t2", "DVB_T2_TABLE_A3")]
T2_SHORT = [("3_5_t2", "DVB_T2_TABLE_B3")]
used = sorted({t for _, t in mapping(normal) + mapping(short) + T2_NORMAL + T2_SHORT})
print("/* Generated by gen/gen_ldpc_tables.py from gr-dvbs2rx (GPL-3.0-or-later).")
print(" * Tables from ETSI EN 302 307-1 Annexes B/C, EN 302 307-2 and EN 302 755")
print(" * Annexes A/B. */")
for name in used:
    t = tables[name]
    for field in ("DEG", "LEN", "POS"):
        vals = t[field]
        print(f"static const uint16_t {name}_{field}[] = {{")
        for i in range(0, len(vals), 12):
            print("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
        print("};")
    print(f"static const struct ldpc_table {name} = {{ {t['M']}, {t['N']}, {t['K']}, "
          f"{t['LINKS_MAX_CN']}, {t['LINKS_TOTAL']}, {t['DEG_MAX']}, "
          f"{name}_DEG, {name}_LEN, {name}_POS }};")
for label, text, extra in (("normal", normal, T2_NORMAL), ("short", short, T2_SHORT)):
    print(f"static const struct ldpc_map ldpc_map_{label}[] = {{")
    for rate, name in mapping(text) + extra:
        print(f'    {{ "{rate}", &{name} }},')
    print("};")
