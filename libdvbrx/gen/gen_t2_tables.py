#!/usr/bin/env python3
"""Generates src/t2_tables.h: the DVB-T2 (EN 302 755) tables the receiver
needs, taken from gr-dtv's transmitter sources (which hold them as C++
arrays): P1 active carriers and S1/S2 patterns (table 68, 69), frame-level
PN sequence (table 56), continual pilot groups (annex G), reserved carriers
for PAPR (annex H), L1 shortening and puncturing orders (tables 40 to 43).

usage: gen_t2_tables.py <gr-dtv/lib/dvbt2 directory> > src/t2_tables.h
"""
import re
import sys

src = sys.argv[1]
texts = {f: open(f"{src}/{f}").read() for f in (
    "dvbt2_p1insertion_cc_impl.cc", "dvbt2_pilotgenerator_cc_impl.cc",
    "dvbt2_framemapper_cc_impl.cc")}


def array(name):
    for t in texts.values():
        m = re.search(r"::" + name + r"(\[[^\]]*\])+\s*=\s*\{(.*?)\};", t, re.S)
        if m:
            return [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\d+", m.group(2))]
    raise SystemExit(f"array {name} not found")


def emit(ctype, name, values, per_line=16):
    print(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        print("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    print("};")


print("/* Generated by gen/gen_t2_tables.py from gr-dtv's DVB-T2 transmitter. */")
print("#ifndef DVBRX_T2_TABLES_H\n#define DVBRX_T2_TABLES_H\n\n#include <stdint.h>\n")
emit("int16_t", "T2_P1_CARRIERS", array("p1_active_carriers"))
emit("uint8_t", "T2_S1_PATTERNS", array("s1_modulation_patterns"))
emit("uint8_t", "T2_S2_PATTERNS", array("s2_modulation_patterns"))
emit("uint8_t", "T2_PN_SEQUENCE", array("pn_sequence_table"))

# continual pilots: groups CP1..CP6 per pattern (absent: empty), extended extras
cp_names = []
for pp in range(1, 9):
    for g in range(1, 7):
        name = f"pp{pp}_cp{g}"
        try:
            v = array(name)
        except SystemExit:
            continue
        emit("int16_t", f"T2_{name.upper()}", v)
        cp_names.append((pp, g, name, len(v)))
ext_names = []
for pp in range(1, 9):
    for fft in ("8k", "16k", "32k"):
        name = f"pp{pp}_{fft}"
        try:
            v = array(name)
        except SystemExit:
            continue
        if name == "pp1_16k" and 3636 in v:
            # gr-dtv's table has a typo: EN 302 755 table G.2 gives 13636
            v = [13636 if x == 3636 else x for x in v]
        emit("int16_t", f"T2_EXT_{name.upper()}", v)
        ext_names.append((pp, fft, name, len(v)))
print("\nstruct t2_cp_group { int pp, group, n; const int16_t* k; };")
print("static const struct t2_cp_group T2_CP_GROUPS[] = {")
for pp, g, name, n in cp_names:
    print(f"    {{ {pp}, {g}, {n}, T2_{name.upper()} }},")
print("};")
print("struct t2_cp_ext { int pp, fft, n; const int16_t* k; };")
print("static const struct t2_cp_ext T2_CP_EXT[] = {")
for pp, fft, name, n in ext_names:
    print(f"    {{ {pp}, {int(fft[:-1]) * 1024}, {n}, T2_EXT_{name.upper()} }},")
print("};")

for fft in ("1k", "2k", "4k", "8k", "16k", "32k"):
    emit("int16_t", f"T2_P2_PAPR_{fft.upper()}", array(f"p2_papr_map_{fft}"))
    emit("int16_t", f"T2_TR_PAPR_{fft.upper()}", array(f"tr_papr_map_{fft}"))

emit("uint8_t", "T2_PRE_PUNCTURE", array("pre_puncture"))
emit("uint8_t", "T2_POST_PADDING_BQPSK", array("post_padding_bqpsk"))
emit("uint8_t", "T2_POST_PADDING_16QAM", array("post_padding_16qam"))
emit("uint8_t", "T2_POST_PADDING_64QAM", array("post_padding_64qam"))
emit("uint8_t", "T2_POST_PUNCTURE_BQPSK", array("post_puncture_bqpsk"))
emit("uint8_t", "T2_POST_PUNCTURE_16QAM", array("post_puncture_16qam"))
emit("uint8_t", "T2_POST_PUNCTURE_64QAM", array("post_puncture_64qam"))
print("\n#endif")
